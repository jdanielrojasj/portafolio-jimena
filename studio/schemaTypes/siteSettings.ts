import {defineField, defineType} from 'sanity'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Ajustes de la web',
  type: 'document',
  groups: [
    {name: 'hero', title: 'Portada', default: true},
    {name: 'about', title: 'Sobre mí'},
    {name: 'contact', title: 'Contacto'},
    {name: 'optional', title: 'Secciones opcionales'},
  ],
  fields: [
    defineField({
      name: 'tagline',
      title: 'Línea de presentación',
      type: 'localeString',
      group: 'hero',
      description: 'La frase bajo tu nombre. Por ejemplo: "Actriz y creadora de contenido UGC".',
    }),
    defineField({
      name: 'heroPhotos',
      title: 'Fotos de portada',
      type: 'array',
      group: 'hero',
      of: [{type: 'image', options: {hotspot: true, storeOriginalFilename: false}}],
      description:
        'Hasta 2 fotos verticales, a ser posible de la misma sesión. Van a los lados del vídeo.',
      validation: (rule) => rule.max(2).error('Como máximo 2 fotos.'),
    }),
    defineField({
      name: 'heroVideo',
      title: 'Vídeo de portada',
      type: 'file',
      group: 'hero',
      options: {accept: 'video/mp4', storeOriginalFilename: false},
      description:
        'Montaje corto y vertical (unos 10 segundos) que se repite sin sonido. Debe ser ligero: menos de 8 MB.',
    }),
    defineField({
      name: 'shareImage',
      title: 'Foto para compartir',
      type: 'image',
      group: 'hero',
      options: {hotspot: true, storeOriginalFilename: false},
      description:
        'Opcional. Foto horizontal que se ve al compartir el enlace en WhatsApp, Instagram o LinkedIn. Si no pones ninguna, se usa la primera foto de portada.',
    }),
    defineField({
      name: 'marqueeWords',
      title: 'Palabras de la franja',
      type: 'array',
      group: 'hero',
      of: [{type: 'localeString'}],
      description: 'Palabras que corren en la franja oscura. Por ejemplo: UGC, Reviews, Teatro.',
    }),
    defineField({
      name: 'aboutText',
      title: 'Texto de presentación',
      type: 'localeText',
      group: 'about',
      description: 'Un párrafo breve sobre ti.',
    }),
    defineField({
      name: 'aboutPhoto',
      title: 'Foto de presentación',
      type: 'image',
      group: 'about',
      options: {hotspot: true, storeOriginalFilename: false},
      description: 'Opcional. Un retrato vertical.',
    }),
    defineField({
      name: 'languages',
      title: 'Idiomas que hablas',
      type: 'array',
      group: 'about',
      of: [{type: 'localeString'}],
      description: 'Un idioma por línea. Por ejemplo: "Español (nativo)".',
    }),
    defineField({
      name: 'email',
      title: 'Correo de contacto',
      type: 'string',
      group: 'contact',
      description: 'Se muestra en público en la web.',
      validation: (rule) => rule.email().error('No parece un correo válido.'),
    }),
    defineField({
      name: 'instagramUrl',
      title: 'Instagram',
      type: 'url',
      group: 'contact',
      description: 'Dirección completa de tu perfil, empezando por https://',
    }),
    defineField({
      name: 'tiktokUrl',
      title: 'TikTok',
      type: 'url',
      group: 'contact',
      description: 'Opcional. Dirección completa de tu perfil, empezando por https://',
    }),
    defineField({
      name: 'showBrands',
      title: 'Mostrar franja de marcas',
      type: 'boolean',
      group: 'optional',
      description:
        'Actívalo cuando tengas varias marcas añadidas. Mientras esté apagado, la franja no aparece.',
      initialValue: false,
    }),
    defineField({
      name: 'showCasting',
      title: 'Mostrar ficha de casting',
      type: 'boolean',
      group: 'optional',
      description: 'Muestra altura, pelo y ojos en la sección de actriz.',
      initialValue: false,
    }),
    defineField({
      name: 'casting',
      title: 'Datos de casting',
      type: 'object',
      group: 'optional',
      description: 'Solo se muestran si la ficha de casting está activada.',
      fields: [
        defineField({
          name: 'height',
          title: 'Altura',
          type: 'string',
          description: 'Por ejemplo: 1,62 m',
        }),
        defineField({name: 'hair', title: 'Pelo', type: 'localeString'}),
        defineField({name: 'eyes', title: 'Ojos', type: 'localeString'}),
      ],
    }),
  ],
  preview: {prepare: () => ({title: 'Ajustes de la web'})},
})
